"""Parse and aggregate NVIDIA Nsight Compute Stage-1 counters."""

from __future__ import annotations

import csv
from math import isfinite
from pathlib import Path
import statistics
from typing import Mapping, Sequence


FIRST_LEVEL_COUNTER = "l1tex__t_sectors_pipe_lsu_mem_global_op_ld.sum"
GLOBAL_LOAD_REQUESTS_COUNTER = "l1tex__t_requests_pipe_lsu_mem_global_op_ld.sum"
TEX_SOURCE_L2_READ_REQUESTS_COUNTER = "lts__t_requests_srcunit_tex_op_read.sum"
L1_TO_L2_READ_COUNTER = "lts__t_sectors_srcunit_tex_op_read.sum"
L2_READ_WORK_COUNTER = L1_TO_L2_READ_COUNTER
L2_READ_MISS_COUNTER = "lts__t_sectors_op_read_lookup_miss.sum"
HBM_READ_COUNTER = "dram__bytes_read.sum"
DURATION_METRIC = "gpu__time_duration.sum"
NATIVE_UNIT = "32-byte global-load L1TEX sector"
COUNTER_METRICS = (
    FIRST_LEVEL_COUNTER,
    GLOBAL_LOAD_REQUESTS_COUNTER,
    TEX_SOURCE_L2_READ_REQUESTS_COUNTER,
    L1_TO_L2_READ_COUNTER,
    L2_READ_MISS_COUNTER,
    HBM_READ_COUNTER,
    DURATION_METRIC,
)
SUMMARY_METRICS = (
    "first_level_memory_accesses",
    "tex_source_l2_read_requests",
    "l1_miss_demand_to_l2",
    "l1_to_l2_read_traffic",
    "l2_read_work",
    "l2_read_misses",
    "hbm_read_bytes",
    "global_load_requests",
    "sectors_per_request",
    "duration_ns",
)


